# while loop in python 

# increasing a variable and printing it
i = int(input("start number: "))
n = int(input("Ending number: "))
while(i<=n):
    print(i)
    i = i + 1

# Decreaing a variable and printing it
x = int(input("start number: "))
y = int(input("Ending number: "))
while(x>=y):
    print(x)
    x = x - 1
