#  Escape value uses 
char = 'n'
print(f"line A \{char} line B")
print("line A \\n line B") # double backslash is used to escape the backslash in the string
print(r"line A \n line B")  # r prefix for raw string it convert all backslash to literal backslash

print(" \\\" \\' ")
print("This is \\\\ double backslash ")
print("these are /\\/\\/\\/\\/\\ mountains")
